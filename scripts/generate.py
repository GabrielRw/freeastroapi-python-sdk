"""Generate typed resources and schema types from the vendored OpenAPI document.

    python scripts/generate.py           write src/freeastroapi/schemas.py and _generated.py
    python scripts/generate.py --check   fail if they are out of date

spec/freeastro.json is refreshed from production by .github/workflows/sync-spec.yml
(``python3 scripts/spec_sync.py fetch``). Hand-written resources (src/freeastroapi/resources.py)
subclass the generated base classes for geo, moon, sky_events and western so their v0.1
signatures stay unchanged. ``generate(spec)`` is used by the generator's unit tests.
"""

from __future__ import annotations

import json
import keyword
import re
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SPEC_PATH = ROOT / "spec" / "freeastro.json"
PACKAGE = ROOT / "src" / "freeastroapi"
HTTP_METHODS = ("get", "post", "put", "patch", "delete")

# Operations implemented by hand in resources.py (kept for v0.1 compatibility).
HAND_WRITTEN = {
    "v2_geo_search",
    "v1_moon_phase",
    "v1_moon_month",
    "v1_sky_events",
    "v1_western_signs_sun",
    "v1_western_signs_moon",
    "v1_western_signs_rising",
    "v1_western_signs_midheaven",
}
# Resources whose top-level class is hand-written and subclasses `<Name>ResourceBase`.
HAND_WRITTEN_RESOURCES = {"geo", "moon", "sky_events", "western"}
# Method names for operations whose path has nothing after the resource.
EMPTY_NAME = {"v1_sky_events": "list"}
TYPING_NAMES = {"Any", "Literal", "NotRequired", "TypeAlias", "TypedDict", "Union", "Optional"}
RESERVED_ARGS = {"self", "body", "options"}

HEADER = "# Generated by scripts/generate.py from spec/freeastro.json. Do not edit.\n"

# Component name -> Python identifier for the spec being generated (set by `generate`).
SCHEMA_NAMES: dict[str, str] = {}


def build_schema_names(names: list[str]) -> dict[str, str]:
    """Component names become identifiers: ``Model-Input`` -> ``Model_Input``."""
    mapping: dict[str, str] = {}
    used: set[str] = set()
    for raw in names:
        name = re.sub(r"[^A-Za-z0-9_]", "_", raw)
        if not re.match(r"[A-Za-z_]", name):
            name = f"_{name}"
        if keyword.iskeyword(name) or name in TYPING_NAMES:
            name = f"{name}Schema"
        unique, i = name, 2
        while unique in used:
            unique, i = f"{name}{i}", i + 1
        used.add(unique)
        mapping[raw] = unique
    return mapping


def schema_ref(ref: str) -> str:
    raw = ref.rsplit("/", 1)[-1]
    if raw not in SCHEMA_NAMES:
        raise SystemExit(f"unresolved $ref {ref}")
    return SCHEMA_NAMES[raw]


def is_json_type(content_type: str) -> bool:
    return bool(re.match(r"application/json\b", content_type, re.I) or re.search(r"\+json\b", content_type, re.I))


def is_text_type(content_type: str) -> bool:
    return bool(re.match(r"text/|image/svg\+xml|application/(xml|yaml|x-yaml)\b", content_type, re.I)) or bool(
        re.search(r"\+xml\b", content_type, re.I)
    )


def success_response(op: dict[str, Any]) -> tuple[str, Any, list[str]]:
    """The first 2xx response decides the return type: ``(kind, json_schema, content_types)``."""
    codes = sorted(code for code in op.get("responses", {}) if re.fullmatch(r"2\d\d", str(code)))
    content = (op["responses"][codes[0]] or {}).get("content", {}) if codes else {}
    # Text types first so content negotiation (e.g. a mock server) prefers what we decode.
    types = sorted(content, key=lambda t: (not is_text_type(t), t))
    json_type = next((t for t in sorted(content) if is_json_type(t)), None)
    if json_type:
        return "json", (content[json_type] or {}).get("schema"), types
    if not types:
        return "json", None, types
    return ("text" if any(is_text_type(t) for t in types) else "bytes"), None, types


def snake(text: str) -> str:
    text = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", text)
    return "_".join(part.lower() for part in re.split(r"[^A-Za-z0-9]+", text) if part)


def pascal(text: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^A-Za-z0-9]+", text) if part)


def is_param(segment: str) -> bool:
    return segment.startswith("{") and segment.endswith("}")


def py_ident(name: str) -> str:
    ident = snake(name) or "value"
    if keyword.iskeyword(ident) or ident in RESERVED_ARGS:
        ident += "_"
    return ident


def docstring(lines: list[str | None], indent: str) -> str:
    text = "\n".join(line for line in lines if line and line.strip()).replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    if not text:
        return ""
    body = "\n".join(f"{indent}{line}".rstrip() if line else "" for line in text.split("\n"))
    return f'{indent}"""{body.lstrip()}\n{indent}"""\n' if "\n" in text else f'{indent}"""{text}"""\n'


# ---------------------------------------------------------------- schema -> Python types

CONSTRAINT_KEYS = {"required", "not", "title", "description", "minProperties", "maxProperties"}


def shape_union(schema: dict[str, Any]) -> list[dict[str, Any]] | None:
    union = schema.get("anyOf") or schema.get("oneOf")
    if not isinstance(union, list):
        return None
    if all(isinstance(s, dict) and set(s) <= CONSTRAINT_KEYS for s in union):
        return None
    return union


def literal_value(value: Any) -> str | None:
    if isinstance(value, bool):
        return "True" if value else "False"
    if value is None:
        return "None"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    return None


def union_of(members: list[str], modern: bool = False) -> str:
    unique: list[str] = []
    for member in members:
        if member not in unique:
            unique.append(member)
    if "Any" in unique:
        return "Any"
    if len(unique) == 1:
        return unique[0]
    if modern:
        return " | ".join(unique)
    return f"Union[{', '.join(unique)}]"


def py_type(schema: Any, ref_prefix: str, quote_refs: bool) -> str:
    if not isinstance(schema, dict) or not schema:
        return "Any"
    if "$ref" in schema:
        name = ref_prefix + schema_ref(schema["$ref"])
        return json.dumps(name) if quote_refs else name
    if "const" in schema:
        value = literal_value(schema["const"])
        return f"Literal[{value}]" if value is not None else "Any"
    if isinstance(schema.get("enum"), list):
        values = [literal_value(v) for v in schema["enum"]]
        if values and all(v is not None for v in values):
            return f"Literal[{', '.join(dict.fromkeys(v for v in values if v is not None))}]"
        return "Any"
    union = shape_union(schema)
    if union is not None:
        return union_of([py_type(s, ref_prefix, quote_refs) for s in union], modern=not quote_refs)
    if isinstance(schema.get("allOf"), list):
        members = schema["allOf"]
        return py_type(members[0], ref_prefix, quote_refs) if len(members) == 1 else "Any"
    kind = schema.get("type")
    if isinstance(kind, list):
        return union_of([py_type({**schema, "type": k}, ref_prefix, quote_refs) for k in kind], modern=not quote_refs)
    if kind == "string":
        return "str"
    if kind == "integer":
        return "int"
    if kind == "number":
        return "float"
    if kind == "boolean":
        return "bool"
    if kind == "null":
        return "None"
    if kind == "array":
        return f"list[{py_type(schema.get('items'), ref_prefix, quote_refs)}]"
    if kind == "object" or "properties" in schema or "additionalProperties" in schema:
        extra = schema.get("additionalProperties")
        if not schema.get("properties") and isinstance(extra, dict) and extra:
            return f"dict[str, {py_type(extra, ref_prefix, quote_refs)}]"
        return "dict[str, Any]"
    return "Any"


def is_typed_dict(schema: dict[str, Any]) -> bool:
    return bool(schema.get("properties")) and shape_union(schema) is None and "allOf" not in schema


def render_schemas(schemas: dict[str, Any]) -> str:
    out = [
        HEADER,
        '"""Request and response shapes from the FreeAstroAPI OpenAPI document, as TypedDicts.\n\n'
        "Forward references are quoted and unions use ``Union`` so the TypedDicts stay correct at\n"
        'runtime (``__required_keys__``) without postponed annotations.\n"""\n',
        "# ruff: noqa: E501, UP007\n",
        "from typing import Any, Literal, NotRequired, TypeAlias, TypedDict, Union",
    ]
    names: list[str] = []
    for raw, schema in schemas.items():
        name = SCHEMA_NAMES[raw]
        names.append(name)
        renamed = f"Schema ``{raw}`` in the OpenAPI document." if name != raw else None
        doc = docstring([schema.get("description"), renamed], "    ")
        if is_typed_dict(schema):
            required = set(schema.get("required", []))
            fields: list[tuple[str, str]] = []
            for key, prop in schema["properties"].items():
                annotation = py_type(prop, "", True)
                fields.append((key, annotation if key in required else f"NotRequired[{annotation}]"))
            if all(re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", k) and not keyword.iskeyword(k) for k, _ in fields):
                body = doc + "".join(f"    {key}: {annotation}\n" for key, annotation in fields)
                body = body or "    pass\n"
                out.append(f"\n\nclass {name}(TypedDict):\n{body}".rstrip("\n"))
            else:
                items = "".join(f"        {json.dumps(key)}: {annotation},\n" for key, annotation in fields)
                out.append(f"\n\n{name} = TypedDict(\n    {json.dumps(name)},\n    {{\n{items}    }},\n)")
        else:
            out.append(f"\n\n{name}: TypeAlias = {py_type(schema, '', True)}")
    out.append("\n\n__all__ = [\n" + "".join(f"    {json.dumps(n)},\n" for n in sorted(names)) + "]\n")
    return "\n".join(out[:4]) + "\n" + "\n".join(out[4:])


# ---------------------------------------------------------------- operations


def collect_operations(spec: dict[str, Any]) -> list[dict[str, Any]]:
    ops: list[dict[str, Any]] = []
    for path, item in spec["paths"].items():
        for method in HTTP_METHODS:
            op = item.get(method)
            if not op:
                continue
            if path == "/natal":
                version, segments = 1, ["natal", "simple"]
            else:
                match = re.match(r"^/api/v(\d+)/(.*)$", path)
                if not match:
                    raise SystemExit(f"unexpected public path {path}")
                version, segments = int(match[1]), [s for s in match[2].split("/") if s]
            params = [p for p in op.get("parameters", []) if p["in"] in ("path", "query")]
            body_content = op.get("requestBody", {}).get("content", {})
            body_type = next((t for t in sorted(body_content) if is_json_type(t)), None)
            if op.get("requestBody") and body_type is None:
                raise SystemExit(
                    f"{op['operationId']}: request body types {', '.join(body_content) or '(none)'} are not "
                    "supported; only JSON bodies are"
                )
            body = body_content.get(body_type) if body_type else None
            kind, json_schema, content_types = success_response(op)
            ops.append(
                {
                    "id": op["operationId"],
                    "method": method.upper(),
                    "path": path,
                    "op": op,
                    "version": version,
                    "resource": snake(segments[0]),
                    "rest": segments[1:],
                    "path_params": [p for p in params if p["in"] == "path"],
                    "query_params": [p for p in params if p["in"] == "query"],
                    "body": None if body is None else body.get("schema", {}),
                    "body_required": bool(op.get("requestBody", {}).get("required")),
                    "json": json_schema,
                    "response_kind": kind,
                    "response_types": content_types,
                }
            )
    return ops


def assign_names(ops: list[dict[str, Any]]) -> None:
    direct = set()
    for o in ops:
        literal_rest = [s for s in o["rest"] if not is_param(s)]
        if len(literal_rest) == 1:
            direct.add((o["resource"], literal_rest[0]))
    for o in ops:
        literal_rest = [s for s in o["rest"] if not is_param(s)]
        sub = None
        name_parts = literal_rest
        if len(literal_rest) >= 2 and not is_param(o["rest"][0]) and (o["resource"], o["rest"][0]) not in direct:
            sub = snake(o["rest"][0])
            name_parts = literal_rest[1:]
        o["sub"] = sub
        o["base_name"] = snake("-".join(name_parts)) if name_parts else EMPTY_NAME.get(o["id"], "get")
    groups: dict[tuple[str, str | None, str], list[dict[str, Any]]] = defaultdict(list)
    for o in ops:
        groups[(o["resource"], o["sub"], o["base_name"])].append(o)
    for group in groups.values():
        latest = max(o["version"] for o in group)
        if len({o["version"] for o in group}) != len(group):
            raise SystemExit(f"name clash: {[o['id'] for o in group]}")
        for o in group:
            o["name"] = o["base_name"] if o["version"] == latest else f"{o['base_name']}_v{o['version']}"
    members: dict[str, str] = {}
    for o in ops:
        o["accessor"] = [o["resource"], *([o["sub"]] if o["sub"] else []), o["name"]]
        top = f"{o['resource']}.{o['sub'] or o['name']}"
        kind = "sub" if o["sub"] else "method"
        if members.setdefault(top, kind) != kind:
            raise SystemExit(f"member clash on {top}")


def class_name(resource: str, sub: str | None, is_async: bool) -> str:
    prefix = "Async" if is_async else ""
    if sub:
        return f"{prefix}{pascal(resource)}{pascal(sub)}Resource"
    suffix = "ResourceBase" if resource in HAND_WRITTEN_RESOURCES else "Resource"
    return f"{prefix}{pascal(resource)}{suffix}"


def response_note(o: dict[str, Any]) -> str | None:
    types = ", ".join(o["response_types"])
    if o["response_kind"] == "bytes":
        return f"\nReturns the response body ({types}) as bytes."
    if o["response_kind"] != "text":
        return None
    if all(is_text_type(t) for t in o["response_types"]):
        return f"\nReturns the response body ({types}) as text."
    return (
        f"\nReturns the response body ({types}) as text; for binary formats such as PNG call\n"
        f'``client.request("{o["method"]}", "{o["path"]}", ..., response_type="bytes")``.'
    )


def render_method(o: dict[str, Any], is_async: bool) -> str:
    args = ["self"]
    for p in o["path_params"]:
        args.append(f"{py_ident(p['name'])}: {py_type(p.get('schema'), 'schemas.', False)}")
    if o["body"] is not None:
        body_type = py_type(o["body"], "schemas.", False)
        args.append(f"body: {body_type}" if o["body_required"] else f"body: {body_type} | None = None")
    args.append("*")
    query_map: list[tuple[str, str]] = []
    required_query = [p for p in o["query_params"] if p.get("required")]
    optional_query = [p for p in o["query_params"] if not p.get("required")]
    for p in required_query + optional_query:
        ident = py_ident(p["name"])
        annotation = py_type(p.get("schema"), "schemas.", False)
        if p.get("required"):
            args.append(f"{ident}: {annotation}")
        else:
            if annotation != "Any" and "None" not in annotation.split(" | "):
                annotation = f"{annotation} | None"
            args.append(f"{ident}: {annotation} = None")
        query_map.append((p["name"], ident))
    args.append("options: RequestOptions | None = None")

    if o["response_kind"] == "text":
        returns = "str"
    elif o["response_kind"] == "bytes":
        returns = "bytes"
    elif o["json"]:
        returns = py_type(o["json"], "schemas.", False)
    else:
        returns = "Any"

    path_expr = json.dumps(o["path"])
    if o["path_params"]:
        path_expr = "f" + json.dumps(
            re.sub(r"\{([^}]+)\}", lambda m: "{_path(" + py_ident(m[1]) + ")}", o["path"])
        )
    params_expr = "_query({" + ", ".join(f"{json.dumps(k)}: {v}" for k, v in query_map) + "})" if query_map else "None"
    json_expr = "body" if o["body"] is not None else "None"

    summary = o["op"].get("summary") or o["id"]
    description = (o["op"].get("description") or "").strip().split("\n\n")[0].strip()
    doc = docstring(
        [
            summary,
            "" if not description or description == summary else "\n" + description,
            f"\n``{o['method']} {o['path']}``",
            response_note(o),
            "\n.. deprecated:: this operation is deprecated by the API." if o["op"].get("deprecated") else None,
        ],
        "        ",
    )
    extra = ""
    if o["response_kind"] != "json":
        extra = f", accept={json.dumps(', '.join(o['response_types']))}, response_type={json.dumps(o['response_kind'])}"
    call = (
        f"self._client.request({json.dumps(o['method'])}, {path_expr}, "
        f"params={params_expr}, json={json_expr}, options=options{extra})"
    )
    prefix = "async def" if is_async else "def"
    awaited = f"await {call}" if is_async else call
    signature = ",\n        ".join(args)
    if returns == "Any":
        ret_stmt = f"        return {awaited}\n"
    else:
        ret_stmt = f"        return cast({json.dumps(returns)}, {awaited})\n"
    return f"    {prefix} {o['name']}(\n        {signature},\n    ) -> {returns}:\n{doc}{ret_stmt}"


def render_resources(ops: list[dict[str, Any]]) -> str:
    resources: dict[str, dict[str, Any]] = {}
    for o in ops:
        r = resources.setdefault(o["resource"], {"methods": [], "subs": defaultdict(list)})
        if o["sub"]:
            r["subs"][o["sub"]].append(o)
        else:
            r["methods"].append(o)

    out = [
        HEADER,
        '"""Resource classes for every public operation. See scripts/generate.py."""\n',
        "# ruff: noqa: E501",
        "from __future__ import annotations\n",
        "from dataclasses import dataclass",
        "from typing import TYPE_CHECKING, Any, Literal, cast",
        "from urllib.parse import quote\n",
        "from . import schemas\n",
        "if TYPE_CHECKING:",
        "    from .client import AsyncFreeAstro, FreeAstro, RequestOptions\n\n",
        "def _query(values: dict[str, Any]) -> dict[str, Any]:",
        "    return {key: value for key, value in values.items() if value is not None}\n\n",
        "def _path(value: object) -> str:",
        '    return quote(str(value), safe="")\n',
    ]
    top_level: dict[bool, list[tuple[str, str]]] = {False: [], True: []}
    for is_async in (False, True):
        client_type = "AsyncFreeAstro" if is_async else "FreeAstro"
        for resource in sorted(resources):
            r = resources[resource]
            subs = [
                (sub, [o for o in items if o["id"] not in HAND_WRITTEN])
                for sub, items in r["subs"].items()
            ]
            subs = [(sub, items) for sub, items in subs if items]
            for sub, items in subs:
                out.append(f"\nclass {class_name(resource, sub, is_async)}:")
                out.append(f"    def __init__(self, client: {client_type}) -> None:\n        self._client = client\n")
                out.extend(render_method(o, is_async) for o in items)
            name = class_name(resource, None, is_async)
            top_level[is_async].append((resource, name))
            out.append(f"\nclass {name}:")
            init = [f"    def __init__(self, client: {client_type}) -> None:", "        self._client = client"]
            init += [f"        self.{sub} = {class_name(resource, sub, is_async)}(client)" for sub, _ in subs]
            out.append("\n".join(init) + "\n")
            out.extend(render_method(o, is_async) for o in r["methods"] if o["id"] not in HAND_WRITTEN)

    for is_async in (False, True):
        prefix = "Async" if is_async else ""
        client_type = "AsyncFreeAstro" if is_async else "FreeAstro"
        generated = [(res, cls) for res, cls in top_level[is_async] if res not in HAND_WRITTEN_RESOURCES]
        out.append(f"\nclass {prefix}GeneratedResources:")
        out.append('    """Resources for the operations outside the hand-written ones."""\n')
        out.extend(f"    {res}: {cls}" for res, cls in generated)
        out.append(f"\n    def _init_generated_resources(self, client: {client_type}) -> None:")
        out.extend(f"        self.{res} = {cls}(client)" for res, cls in generated)
        out.append("")

    out.append(
        "\n@dataclass(frozen=True, slots=True)\nclass OperationInfo:\n"
        "    operation_id: str\n    method: str\n    path: str\n"
        "    accessor: tuple[str, ...]\n    has_body: bool\n    path_params: tuple[str, ...]\n"
        "    required_query: tuple[str, ...]\n    deprecated: bool\n"
    )
    rows = []
    for o in ops:
        required = tuple(py_ident(p["name"]) for p in o["query_params"] if p.get("required"))
        rows.append(
            f"    OperationInfo({json.dumps(o['id'])}, {json.dumps(o['method'])}, {json.dumps(o['path'])}, "
            f"{tuple(o['accessor'])!r}, {o['body'] is not None}, "
            f"{tuple(py_ident(p['name']) for p in o['path_params'])!r}, {required!r}, "
            f"{bool(o['op'].get('deprecated'))}),"
        )
    out.append("#: Every public operation and the client method that calls it.")
    out.append("OPERATIONS: tuple[OperationInfo, ...] = (\n" + "\n".join(rows) + "\n)\n")
    return "\n".join(out)


def generate(spec: dict[str, Any]) -> dict[str, str]:
    """Render the generated modules for an OpenAPI document: ``{file name: source}``."""
    schemas = spec.get("components", {}).get("schemas", {})
    SCHEMA_NAMES.clear()
    SCHEMA_NAMES.update(build_schema_names(list(schemas)))
    ops = collect_operations(spec)
    assign_names(ops)
    return {"schemas.py": render_schemas(schemas), "_generated.py": render_resources(ops)}


def main() -> int:
    spec = json.loads(SPEC_PATH.read_text(encoding="utf-8"))
    files = {PACKAGE / name: text for name, text in generate(spec).items()}
    ops = collect_operations(spec)
    if "--check" in sys.argv:
        stale = [str(p) for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        if stale:
            print(f"out of date: {', '.join(stale)}; run python scripts/generate.py", file=sys.stderr)
            return 1
        print(f"checked {len(ops)} operations")
        return 0
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
    print(f"generated {len(ops)} operations, {len(spec['components']['schemas'])} schemas")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
